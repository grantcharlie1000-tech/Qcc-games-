import { test, expect } from '../../fixtures';
import { createNativeFixture, nativeViewSave, nativeWorkerSummary, observeNativeWorkers, queryNativeFixtureValue, selectNativeFixture, waitForNativeMap } from './native-fixture';

test('replacing a loaded map and a blocked worker cleans both before the next source becomes ready', async ({ page }, info) => {
  test.setTimeout(60_000);
  await observeNativeWorkers(page);
  await page.setViewportSize({ width: 1024, height: 768 });
  const first = await createNativeFixture(info, 'first-base');
  const marker = 'NATIVE_E2E_REPLACEMENT_ENTERED';
  const blocked = await createNativeFixture(info, 'blocked-replacement', { baseLua: `print("${marker}"); while true do end` });
  const final = await createNativeFixture(info, 'final-base', { firstProvinceId: 11 });
  await page.goto('/#/game/iron-meridian');
  const firstCreated = page.waitForEvent('worker');
  await selectNativeFixture(page, first);
  const firstWorker = await firstCreated;
  const firstSnapshot = await waitForNativeMap(page);
  await page.locator('.im-native-map').click({ position: { x: 256, y: 384 } });
  await expect(page.locator('.im-native-selection')).toHaveAttribute('data-province-id', '1');
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click();
  await expect.poll(async () => (await nativeViewSave(page))?.camera.zoom).toBe(2);
  const firstClosed = firstWorker.waitForEvent('close');
  const secondCreated = page.waitForEvent('worker');
  const enteredLua = page.waitForEvent('console', message => message.text().includes(marker));
  await selectNativeFixture(page, blocked);
  const secondWorker = await secondCreated;
  await firstClosed; await enteredLua;
  await expect(page.locator('.im-native')).toHaveAttribute('data-state', 'loading');
  await expect(page.locator('.im-native-selection')).toBeHidden();
  await expect(page.getByRole('navigation', { name: 'Map controls', exact: true })).toBeHidden();
  expect(await page.locator('.im-native-map').evaluate(canvas => Array.from((canvas as HTMLCanvasElement).getContext('2d')!.getImageData(0, 0, 1, 1).data))).toEqual([18, 38, 56, 255]);
  const secondClosed = secondWorker.waitForEvent('close');
  await selectNativeFixture(page, final);
  await secondClosed;
  const finalSnapshot = await waitForNativeMap(page);
  expect(finalSnapshot).not.toBe(firstSnapshot);
  expect(await queryNativeFixtureValue(page)).toEqual({ type: 'number', value: 32 });
  await page.locator('.im-native-map').click({ position: { x: 256, y: 384 } });
  await expect(page.locator('.im-native-selection')).toHaveAttribute('data-province-id', '11');
  await expect.poll(async () => (await nativeViewSave(page))?.snapshotId).toBe(finalSnapshot);
  expect((await nativeViewSave(page))?.camera).toEqual({ x: 64, y: 32, zoom: 1 });
  expect((await nativeWorkerSummary(page)).map(worker => worker.terminated)).toEqual([true, true, false]);
  await page.screenshot({ path: info.outputPath('native-replacement.png') });
});
