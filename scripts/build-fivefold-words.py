"""Regenerate src/games/fivefold/words.ts (run: python3 scripts/build-fivefold-words.py <source-dir>).

<source-dir> must contain:
  a5.txt          five-letter lines of 12dicts-6.0.2 American/3esl.txt (public domain, Alan Beale)
                  https://downloads.sourceforge.net/wordlist/12dicts-6.0.2.zip
                  sha256 64ac1d35acb66b550c7ebc56e080b62e0bad8f5984d72059dc2e05ac48780e52
  g5.txt          five-letter lines of ENABLE enable1.txt (public domain)
                  https://raw.githubusercontent.com/dolph/dictionary/master/enable1.txt
  ldnoobw-en.txt  build-time filter only, not shipped (CC BY 4.0)
                  https://github.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words
Extract with: tr -d '\r' < FILE | grep -E '^[a-z]{5}$'
"""
import os, sys
os.chdir(sys.argv[1])
import random
bad=set(w.strip() for w in open('ldnoobw-en.txt') if w.strip())
manual=set("""abort bigot bimbo booty booze bosom bowel buxom chink craps feces fetal fetus gypsy harem horny idiot lynch moron nappy opium pansy pubic pygmy queer retch semen sperm spank sissy slave thong urine uteri vodka vomit welsh whore nymph ovary prick pussy kinky grope bitch fanny screw sheik swine lusty bawdy balls pinup mucus polyp obese leper drunk junta gonna gotta wanna sexy dicks tramp bimbo darky wench hussy""".split())
american=set("color favor honor armor ardor valor vapor humor labor rumor savor tumor fiber liter saber rigor vigor furor".split())
a=[w.strip() for w in open('a5.txt')]
g=set(w.strip() for w in open('g5.txt'))
answers=sorted(w for w in a if w in g and w not in bad and w not in manual and w not in american)
slurs=set(w for w in bad if len(w)==5)|set("chink gypsy pansy queer whore pussy bitch nigga negro dykes faggy kikes spick spics wetback coons gooks".split())
guesses=sorted((g|set(answers))-slurs)
rng=random.Random(20261027); order=answers[:]; rng.shuffle(order)
print(len(answers),len(guesses))
out=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','src','games','fivefold','words.ts')
head='''// Generated by scripts/build-fivefold-words.py. Do not edit by hand.
// Answers: five-letter words from 3esl.txt in 12dicts 6.0.2 by Alan Beale (public domain),
// kept only if also in ENABLE, minus offensive, sensitive and US-only spellings; fixed shuffled order.
// Guesses: five-letter words from ENABLE (enable1, public domain) plus all answers, minus slurs.
// See src/games/fivefold/WORDS.md for sources, licences and filtering.
'''
open(os.path.abspath(out),'w').write(head+"export const ANSWERS:readonly string[]='"+' '.join(order)+"'.split(' ');\nexport const GUESSES:readonly string[]='"+' '.join(guesses)+"'.split(' ');\n")
