/** Builds the Breachline cover and title SVG strings. Pure and deterministic. */
import { CARD } from './palette.ts';
import { ROOM, buildScene } from './scene.ts';
import { pathsSvg, polygonCount, rasterise, toScreen, hash, type Polys, type View } from './voxel.ts';

export const COVER = { w: 320, h: 410, band: 95 } as const;

function bounds(polys: Polys) {
  let x0 = Infinity, x1 = -Infinity, y0 = Infinity, y1 = -Infinity;
  for (const p of polys) for (const l of p.loops) for (const [X, Y] of l) { x0 = Math.min(x0, X); x1 = Math.max(x1, X); y0 = Math.min(y0, Y); y1 = Math.max(y1, Y); }
  return { x0, x1, y0, y1 };
}

/** Fit lattice bounds into a box: width may overflow (the card crops), height must fit. */
function fit(polys: Polys, box: { x0: number; x1: number; y0: number; y1: number }, widthScale = 1): View {
  const b = bounds(polys);
  const s = Math.min(((box.x1 - box.x0) * widthScale) / (b.x1 - b.x0), (box.y1 - box.y0) / ((b.y1 - b.y0) / 2));
  return { s, ox: (box.x0 + box.x1) / 2 - s * (b.x0 + b.x1) / 2, oy: box.y1 - s * b.y1 / 2 };
}

export type Built = { svg: string; polygons: number };

export function generateCover(): Built {
  const polys = rasterise(buildScene());
  // Anchor the middle of the hole on the card and crop the room's corners.
  const s = 5.2, hole = { X: ROOM.holeX - (ROOM.wallY + 2), Y: ROOM.holeX + ROOM.wallY + 2 - 2 * ROOM.holeZ };
  const view: View = { s, ox: 166 - s * hole.X, oy: 262 - (s * hole.Y) / 2 };
  // Dust motes in the light from the hole.
  const [hx, hy] = toScreen(view, hole.X, hole.Y + 16);
  let dust = '';
  for (let i = 0; i < 18; i++) {
    const x = hx + (hash(i, 0, 0, 7) - 0.6) * 70, y = hy + (hash(i, 1, 0, 7) - 0.7) * 70, s = hash(i, 2, 0, 7) < 0.3 ? 2 : 1.5;
    if (y < COVER.band + 12) continue;
    dust += `M${x.toFixed(1)} ${y.toFixed(1)}h${s}v${s}h-${s}Z`;
  }
  const svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${COVER.w} ${COVER.h}" role="img" aria-labelledby="title desc"><title id="title">Attackers breaching an office wall as defenders hold behind cover</title><desc id="desc">Original Breachline voxel cover: a cutaway office and lab room, a ragged hole blown through a partition with amber light and debris pouring in, a blue-banded attacker stepping through, orange-banded defenders behind an overturned desk and a barricade, and the uplink glowing on a table. Generated by scripts/breachline-assets/titlecard.</desc>
<path fill="${CARD.bg}" d="M0 0h${COVER.w}v${COVER.h}H0Z"/>${pathsSvg(polys, view)}<path fill="#ffd98a" fill-opacity=".55" d="${dust}"/></svg>
`;
  return { svg, polygons: polygonCount(polys) };
}
